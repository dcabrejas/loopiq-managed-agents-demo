#!/usr/bin/env python3
"""Generate acme.yaml and globex.yaml from one template, embedding SKILL.md.

The two customers are identical except for their name, repo and secret.
Run after editing SKILL.md or the template, then ./setup.sh to recreate the configs.
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
CUSTOMERS = [("acme", "Acme"), ("globex", "Globex")]

skill = (HERE / "SKILL.md").read_text()
front, body = re.match(r"---\n(.*?)\n---\n(.*)", skill, re.S).groups()
description = re.search(r"description: (.*)", front).group(1)
instructions = "\n".join(("      " + l) if l else "" for l in body.strip().splitlines())

TEMPLATE = """# LoopIQ demo: release certifier for customer "{name}".
# Generated by build-specs.py. One spec per customer: own sandbox, own secret, own repo.
name: loopiq-{slug}
agent: claude-code
size: mars-1vcpu-1gb
env:
  CUSTOMER: "{name}"
  RELEASE_REPO: "dcabrejas/loopiq-demo-{slug}"
  # Claude Code runs on DigitalOcean Serverless Inference (Anthropic-compatible API)
  ANTHROPIC_BASE_URL: "https://inference.do-ai.run"
  ANTHROPIC_MODEL: deepseek-v4-pro-0813
  ANTHROPIC_SMALL_FAST_MODEL: deepseek-v4-pro-0813
  CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: "1"
secrets:
  ANTHROPIC_API_KEY: {{}}      # DO model access key
  CUSTOMER_API_KEY: {{}}       # this customer's own credential (fake, for the isolation demo)
egress:
  allow_hosts:
    - inference.do-ai.run     # the model. GitHub is reached only through Action Gateway.
tools:
  - do.actions:
      tools:
        - github_list_pull_requests
        - github_get_pull_request
        - github_list_pr_files
        - github_get_content
        - github_create_pr_review
        - github_update_pull_request
      preload_tools:
        - github_list_pull_requests
        - github_get_pull_request
        - github_list_pr_files
        - github_get_content
        - github_create_pr_review
permissions:
  default: allow
  rules:
    # Reads run freely
    - tool: do.actions/github_list_pull_requests
      action: allow
    - tool: do.actions/github_get_pull_request
      action: allow
    - tool: do.actions/github_list_pr_files
      action: allow
    - tool: do.actions/github_get_content
      action: allow
    # Posting the certification needs a human (enforced by Action Gateway)
    - tool: do.actions/github_create_pr_review
      action: ask
      enforcement: strict
    # The agent can never change the release itself
    - tool: do.actions/github_update_pull_request
      action: deny
skills:
  - name: release-certification
    description: "{description}"
    instructions: |
{instructions}
"""

for slug, name in CUSTOMERS:
    out = HERE / f"{slug}.yaml"
    out.write_text(TEMPLATE.format(slug=slug, name=name, description=description, instructions=instructions))
    print(f"wrote {out.name}")
